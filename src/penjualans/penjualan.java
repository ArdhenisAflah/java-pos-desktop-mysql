    private void tampilkan() {
        Connection con;
        try {
            dfm.setRowCount(0);
            con = DriverManager.getConnection("jdbc:mysql://localhost:3306/program_aplikasi", "root", "");
            ResultSet res = con.createStatement().executeQuery("SELECT *  FROM penjualan ORDER BY id_penjualan DESC");
            while(res.next()){
                String data[] = {res.getString(1),res.getString(2),res.getString(3),res.getString(4),res.getString(5),res.getString(6)};
                dfm.addRow(data);
            }
        } catch (SQLException ex) {
            Logger.getLogger(penjualan.class.getName()).log(Level.SEVERE, null, ex);
        }
        
    }
